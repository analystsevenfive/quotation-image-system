-- Migration 007: Quotations requested by signed-in customers from the storefront cart

CREATE TABLE IF NOT EXISTS web_quote_counters (
    period text PRIMARY KEY,
    last_value integer NOT NULL
);

CREATE TABLE IF NOT EXISTS web_quotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_number text NOT NULL UNIQUE,
    shopify_customer_id text NOT NULL,
    customer_name text,
    customer_email text,
    company text,
    phone text,
    currency text NOT NULL,
    subtotal numeric(14, 2) NOT NULL,
    vat numeric(14, 2) NOT NULL,
    grand_total numeric(14, 2) NOT NULL,
    lines jsonb NOT NULL,
    payment_term text,
    remark text,
    validity_days integer,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS web_quotes_customer_created_idx ON web_quotes(shopify_customer_id, created_at DESC);
ALTER TABLE web_quote_counters ENABLE ROW LEVEL SECURITY;
ALTER TABLE web_quotes ENABLE ROW LEVEL SECURITY;
